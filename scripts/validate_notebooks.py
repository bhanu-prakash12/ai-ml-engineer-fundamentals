#!/usr/bin/env python
"""Execute every notebook across all built days (and the capstone) from a clean kernel and
write a validation report.

For each notebook under any day0N_* directory, plus projects/, that exists:
  1. Execute from a fresh kernel (no reliance on prior notebook state).
  2. Fail loudly on any raised exception (including asserts the notebooks define themselves).
  3. Record wall-clock time and a short status note.
  4. Write reports/notebook_validation.md as a markdown table.

Usage:
    python scripts/validate_notebooks.py            # validate every built day
    python scripts/validate_notebooks.py day01_python_data_math   # validate one day only
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

import nbformat
from nbclient import NotebookClient
from nbclient.exceptions import CellExecutionError

REPO_ROOT = Path(__file__).resolve().parent.parent
REPORT_PATH = REPO_ROOT / "reports" / "notebook_validation.md"


def discover_notebooks(target_dirs: list[Path]) -> list[Path]:
    notebooks = []
    for d in target_dirs:
        notebooks.extend(d.rglob("*.ipynb"))
    return sorted(set(notebooks))


def validate_notebook(path: Path, timeout: int = 900) -> tuple[str, float, str]:
    nb = nbformat.read(path, as_version=4)
    client = NotebookClient(
        nb, timeout=timeout, kernel_name="python3",
        resources={"metadata": {"path": str(path.parent)}},
    )
    start = time.time()
    try:
        client.execute()
        status, note = "PASS", "executed cleanly"
    except CellExecutionError as exc:
        status = "FAIL"
        note = str(exc).splitlines()[0][:160]
    elapsed = time.time() - start
    return status, elapsed, note


def main() -> int:
    if len(sys.argv) > 1:
        target_dirs = [REPO_ROOT / arg for arg in sys.argv[1:]]
    else:
        target_dirs = sorted(REPO_ROOT.glob("day0*")) + [REPO_ROOT / "projects"]

    notebooks = discover_notebooks(target_dirs)
    if not notebooks:
        print(f"No notebooks found under {[str(d) for d in target_dirs]}")
        return 1

    rows = []
    any_failed = False
    for nb_path in notebooks:
        rel = nb_path.relative_to(REPO_ROOT)
        print(f"Validating {rel} ...")
        status, elapsed, note = validate_notebook(nb_path)
        if status == "FAIL":
            any_failed = True
        rows.append((str(rel), status, f"{elapsed:.1f}s", note))
        print(f"  -> {status} ({elapsed:.1f}s) {note}")

    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Notebook Validation Report",
        "",
        f"Generated by `scripts/validate_notebooks.py`. {len(rows)} notebook(s) checked, "
        f"{'all passed' if not any_failed else 'some FAILED — see below'}.",
        "",
        "| Notebook | Status | Time | Notes |",
        "|---|---|---|---|",
    ]
    for rel, status, elapsed, note in rows:
        lines.append(f"| `{rel}` | {status} | {elapsed} | {note} |")
    REPORT_PATH.write_text("\n".join(lines) + "\n")
    print(f"\nReport written to {REPORT_PATH.relative_to(REPO_ROOT)}")

    return 1 if any_failed else 0


if __name__ == "__main__":
    sys.exit(main())
